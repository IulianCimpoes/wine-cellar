-- Winery table
-- =========================
CREATE TABLE winery (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(255) NOT NULL,
                        country VARCHAR(255) NOT NULL,
                        version BIGINT NOT NULL
);

